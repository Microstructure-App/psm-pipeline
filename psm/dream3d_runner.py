"""
Headless DREAM.3D orchestration for the 3-phase generator template.

One call -- generate_microstructure() -- does the whole 3D step with no GUI:
  1. read the template JSON,
  2. inject per-phase (volume fraction, mu, sigma) measured from the SEM,
  3. set the .vtk output path (and optionally volume dims / resolution),
  4. run DREAM.3D's PipelineRunner.exe in the background,
  5. return the absolute path of the .vtk it produced.

FILTERS ARE LOCATED BY NAME, NOT BY KEY
---------------------------------------
DREAM.3D templates number their filters inconsistently. The bundled
3D_generator_simple.json uses single-digit keys ("0", "1", "5"); the lab's
3phasemicrostructure_stl_removeisolated JSON uses zero-padded keys ("00",
"01", "11"). Indexing by key therefore binds this module to exactly one
template and raises KeyError -- or, worse, silently writes into the WRONG
filter -- on the other. ``Filter_Name`` is stable across both conventions, so
every filter here is found by name:

  StatsGeneratorFilter      -> StatsDataArray["1"|"2"|"3"]
      PhaseFraction                                  <- volume fraction
      FeatureSize Distribution / Average             <- mu    (mean of ln D)
      FeatureSize Distribution / Standard Deviation  <- sigma (std of ln D)
  InitializeSyntheticVolume -> Dimensions, Resolution
  VtkRectilinearGridWriter  -> OutputFile
  DataContainerWriter       -> OutputFile          (side output, redirected)
  WriteStlFile              -> OutputStlDirectory  (side output, redirected)

Side outputs are redirected because the lab template ships with hard-coded
Windows paths (e.g. C:/Users/xfjin/...) that either fail outright on another
machine or scatter files somewhere the caller never looks.

NO RANDOM SEED EXISTS
---------------------
Verified against the 6.5.171 template: neither PackPrimaryPhases nor
InitializeSyntheticVolume exposes a seed parameter. DREAM.3D seeds its packing
RNG internally from the clock, so running the SAME pipeline twice produces
DIFFERENT volumes. Two consequences:
  * Replicates are free -- just call generate_microstructure() N times.
  * Generation is NOT reproducible. Archive every volume you intend to report
    (psm.batch saves each one as a compressed .npz), or the numbers in the
    paper cannot be regenerated by anyone, including you.

"Call DREAM.3D" means invoking PipelineRunner.exe (the headless CLI that ships
in the DREAM.3D 6.5.171 bin folder) -- NOT DREAM3D.exe, which opens the GUI.
"""

from __future__ import annotations

import json
import math
import os
import subprocess
from dataclasses import dataclass
from pathlib import Path


@dataclass
class PhaseParams:
    """One phase's stats, in the order the template expects (phase 1, 2, 3)."""
    phase_fraction: float          # area/volume fraction from segmentation
    mu: float                      # lognormal mu  = mean of ln(diameter)
    sigma: float                   # lognormal sigma = std of ln(diameter)
    name: str = ""                 # label only (Pore / NiO / BZCYYb)


# ---------------------------------------------------------------------------
# Filter lookup
# ---------------------------------------------------------------------------
def find_filter_key(pipe: dict, filter_name: str) -> str:
    """Return the JSON key of the filter whose Filter_Name is `filter_name`.

    Raises KeyError naming the filter and listing what the template DOES
    contain, so a template mismatch produces a message a human can act on
    instead of a bare KeyError('5').
    """
    for k, v in pipe.items():
        if isinstance(v, dict) and v.get("Filter_Name") == filter_name:
            return k
    present = sorted(v.get("Filter_Name", "?")
                     for v in pipe.values() if isinstance(v, dict))
    raise KeyError(
        f"This DREAM.3D template contains no '{filter_name}' filter. "
        f"Filters present: {present}"
    )


def find_filter_key_optional(pipe: dict, filter_name: str) -> str | None:
    """Same, but returns None instead of raising (for optional side-output filters)."""
    try:
        return find_filter_key(pipe, filter_name)
    except KeyError:
        return None


# ---------------------------------------------------------------------------
# Pipeline construction
# ---------------------------------------------------------------------------
# ---------------------------------------------------------------------------
# Writing ONE phase -- THE BINS MUST BE REGENERATED
# ---------------------------------------------------------------------------
# StatsGenerator does NOT sample grain diameters from (Average, StdDev). Those
# are metadata. The diameters PackPrimaryPhases actually places come from the
# discretised arrays: BinNumber, Bin Count, Feature_Diameter_Info, and the
# per-bin FeatureSize Vs * distributions.
#
# Setting Average/StdDev while leaving the bins at the template's defaults
# fails SILENTLY. The bundled template is a gold/nickel demo whose phase-1
# grains are 1.1-3.7 um. A 100x100x50 volume at 0.1 um is 500 um^3, so a 1.2%
# pore target is 6 um^3 -- while ONE 3.7 um template grain is 26 um^3, four
# times the entire budget. DREAM.3D therefore placed one or two huge grains,
# overshot to ~20% pore, and did it identically for every sample. Every 3D
# metric computed that way describes the template, not the electrode.
#
# So the bins are rebuilt from (mu, sigma) on every call, and the per-bin
# arrays are rebroadcast to the new bin count.
_CUTOFF_SIGMA = 3.0
_NUM_BINS = 10


def _write_phase(s: dict, name: str, frac: float, mu: float, sigma: float) -> None:
    import numpy as np
    fsd = s.setdefault("FeatureSize Distribution", {})
    # DREAM.3D's JSON parser rejects NaN/Inf; a collapsed lognormal fit (too few
    # particles -- pore is the usual culprit) falls back to the template default
    # so the run survives, but the volume then describes the TEMPLATE. psm.batch
    # flags these psd_ok=False; if you call this module directly, check yourself.
    if not math.isfinite(mu):
        mu = float(fsd.get("Average", 0.7))
    if not math.isfinite(sigma) or sigma <= 0:
        sigma = float(fsd.get("Standard Deviation", 0.2))

    if name:
        s["Name"] = name
    s["PhaseFraction"] = float(frac)
    fsd["Average"] = float(mu)
    fsd["Standard Deviation"] = float(sigma)

    minD = float(np.exp(mu - _CUTOFF_SIGMA * sigma))
    maxD = float(np.exp(mu + _CUTOFF_SIGMA * sigma))
    if not (maxD > minD):
        maxD = minD * 1.5 + 1e-3
    step = (maxD - minD) / _NUM_BINS
    bins = np.arange(minD, maxD, step)
    if bins.size == 0:
        bins = np.array([minD])
    n_bins = int(bins.size)

    s["BinNumber"] = [float(b) for b in bins]
    s["Bin Count"] = n_bins
    s["Feature_Diameter_Info"] = [float(step), float(maxD), float(minD)]

    def _broadcast(dist_key: str, array_keys: list) -> None:
        dist = s.get(dist_key)
        if not isinstance(dist, dict):
            return
        for k in array_keys:
            vals = dist.get(k)
            if isinstance(vals, list) and vals:
                dist[k] = [float(vals[0])] * n_bins

    _broadcast("FeatureSize Vs B Over A Distributions", ["Alpha", "Beta"])
    _broadcast("FeatureSize Vs C Over A Distributions", ["Alpha", "Beta"])
    _broadcast("FeatureSize Vs Omega3 Distributions", ["Alpha", "Beta"])
    _broadcast("FeatureSize Vs Neighbors Distributions",
               ["Average", "Standard Deviation"])


def build_pipeline(
    template_path: str,
    phases: list[PhaseParams],
    output_vtk: str,
    dims: tuple[int, int, int] | None = None,
    resolution_um: float | None = None,
    normalize: bool = True,
) -> str:
    """Write a run-ready pipeline JSON; return its absolute path."""
    if len(phases) != 3:
        raise ValueError(f"This template has exactly 3 phases; got {len(phases)}.")

    with open(template_path, "r") as f:
        pipe = json.load(f)

    k_stats = find_filter_key(pipe, "StatsGeneratorFilter")
    k_init = find_filter_key(pipe, "InitializeSyntheticVolume")
    k_vtk = find_filter_key(pipe, "VtkRectilinearGridWriter")

    # --- phase fractions must sum to 1.0 for DREAM.3D -----------------------
    fr = [float(p.phase_fraction) for p in phases]
    total = sum(fr)
    if total <= 0:
        raise ValueError("All phase fractions are zero; check the segmentation.")
    if normalize and abs(total - 1.0) > 1e-6:
        fr = [x / total for x in fr]  # e.g. drops an "Unclassified" remainder

    # --- StatsGenerator: phase fraction + lognormal (mu, sigma) -------------
    try:
        stats = pipe[k_stats]["StatsDataArray"]
    except KeyError as e:
        raise KeyError(f"StatsGeneratorFilter has no StatsDataArray: {e}")

    phase_keys = sorted((k for k in stats if k.isdigit()), key=int)
    if len(phase_keys) != len(phases):
        raise ValueError(
            f"Template defines {len(phase_keys)} phases but {len(phases)} were "
            f"supplied. Use a 3-phase segmentation or a matching template.")

    for key, ph, frac in zip(phase_keys, phases, fr):
        _write_phase(stats[key], ph.name, float(frac), float(ph.mu), float(ph.sigma))

    # --- volume size / resolution (optional) --------------------------------
    if dims is not None or resolution_um is not None:
        init = pipe[k_init]
        if dims is not None:
            init["Dimensions"] = {"x": int(dims[0]), "y": int(dims[1]),
                                  "z": int(dims[2])}
        if resolution_um is not None:
            init["Resolution"] = {"x": float(resolution_um),
                                  "y": float(resolution_um),
                                  "z": float(resolution_um)}
        # keep the cached display string consistent with Dimensions x Resolution
        d = init["Dimensions"]
        r = init["Resolution"]
        init["BoxDimensions"] = (
            f"X Range: 0 to {d['x']*r['x']} (Delta: {d['x']*r['x']})\n"
            f"Y Range: 0 to {d['y']*r['y']} (Delta: {d['y']*r['y']})\n"
            f"Z Range: 0 to {d['z']*r['z']} (Delta: {d['z']*r['z']})"
        )

    # --- VTK output path (absolute) -----------------------------------------
    out_abs = os.path.abspath(output_vtk)
    os.makedirs(os.path.dirname(out_abs) or ".", exist_ok=True)
    pipe[k_vtk]["OutputFile"] = out_abs

    # --- redirect side outputs (.dream3d, STL) next to the VTK --------------
    side_dir = os.path.join(os.path.dirname(out_abs) or ".", "_side")
    stem = Path(out_abs).stem

    k_dcw = find_filter_key_optional(pipe, "DataContainerWriter")
    k_stl = find_filter_key_optional(pipe, "WriteStlFile")
    if k_dcw or k_stl:
        os.makedirs(side_dir, exist_ok=True)
    if k_dcw:
        pipe[k_dcw]["OutputFile"] = os.path.join(side_dir, stem + ".dream3d")
    if k_stl:
        pipe[k_stl]["OutputStlDirectory"] = side_dir

    # PipelineRunner needs an absolute path to the pipeline too
    json_abs = os.path.abspath(
        os.path.join(os.path.dirname(out_abs) or ".", "_run_pipeline.json")
    )
    with open(json_abs, "w") as f:
        json.dump(pipe, f, indent=2)
    return json_abs


# ---------------------------------------------------------------------------
# Execution
# ---------------------------------------------------------------------------
def run_pipeline(json_path: str, pipeline_runner_exe: str,
                 stream: bool = False) -> subprocess.CompletedProcess:
    """Invoke PipelineRunner.exe headlessly. stream=True prints engine output live."""
    if not os.path.isfile(pipeline_runner_exe):
        raise FileNotFoundError(
            f"PipelineRunner not found at: {pipeline_runner_exe}\n"
            "Point this at <DREAM3D install>/bin/PipelineRunner.exe (NOT DREAM3D.exe)."
        )
    cmd = [pipeline_runner_exe, "-p", os.path.abspath(json_path)]
    if stream:
        return subprocess.run(cmd)  # inherits stdout/stderr -> live errors
    return subprocess.run(cmd, capture_output=True, text=True)


def generate_microstructure(
    template_path: str,
    phases: list[PhaseParams],
    output_vtk: str,
    pipeline_runner_exe: str,
    dims: tuple[int, int, int] | None = None,
    resolution_um: float | None = None,
    stream: bool = False,
    cleanup: bool = False,
) -> str:
    """Full 3D step: build -> run -> verify. Returns absolute .vtk path.

    Raises RuntimeError with captured engine output if the run fails.

    NOTE: no seed is passed, because DREAM.3D 6.5 does not accept one. Calling
    this twice with identical arguments yields two DIFFERENT volumes. That is
    the mechanism psm.batch uses to sample reconstruction noise -- and the
    reason generated volumes must be archived rather than regenerated.
    """
    json_path = build_pipeline(template_path, phases, output_vtk,
                               dims=dims, resolution_um=resolution_um)
    try:
        proc = run_pipeline(json_path, pipeline_runner_exe, stream=stream)
        out_abs = os.path.abspath(output_vtk)
        if proc.returncode != 0 or not os.path.isfile(out_abs):
            tail = ""
            if not stream:
                tail = (proc.stdout or "")[-2000:] + "\n" + (proc.stderr or "")[-2000:]
            raise RuntimeError(
                f"DREAM.3D failed (exit {proc.returncode}); no VTK at {out_abs}.\n{tail}"
            )
        return out_abs
    finally:
        if cleanup and os.path.exists(json_path):
            os.remove(json_path)