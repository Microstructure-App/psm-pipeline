# ===========================================================================
# Specs
# ===========================================================================
@dataclass
class SampleSpec:
    """One sample: its image, its calibration, and its OWN threshold bands.

    ``bands`` is an ordered list of (phase_name, low, high) in 8-bit intensity.
    These are the PER-SAMPLE bands validated against the MATLAB reference --
    they differ between samples because SEM brightness differs between
    samples, which is itself the evidence for the "no universal threshold"
    limitation. They are applied UNCHANGED to every tile.

    ``roi`` is (row0, col0, height, width) applied BEFORE tiling, to strip the
    SEM databar and any dead border. None = use the whole image.
    """
    sample_id: str
    image_path: str
    um_per_px: float
    bands: List[Tuple[str, int, int]]
    roi: Optional[Tuple[int, int, int, int]] = None

    def thresholds(self) -> List[seg.PhaseThreshold]:
        return [seg.PhaseThreshold(n, int(lo), int(hi)) for n, lo, hi in self.bands]

    @property
    def phase_names(self) -> List[str]:
        return [n for n, _, _ in self.bands]


@dataclass
class BatchConfig:
    """Everything that is held constant across the whole sweep."""
    template: str                       # DREAM.3D pipeline template JSON
    runner_exe: str                     # PipelineRunner.exe (headless)
    out_dir: str = "outputs/batch"
    grid: int = 3                       # 3 -> 9 tiles per image
    replicates: int = 10                # DREAM.3D runs per tile
    dims: Tuple[int, int, int] = (100, 100, 50)   # synthetic volume voxels
    voxel_um: float = 0.1               # synthetic voxel edge length
    axes: Tuple[int, ...] = (0, 1, 2)   # tortuosity along z, y, x
    psd_cfg: psdmod.PSDConfig = field(default_factory=psdmod.PSDConfig)
    archive_volumes: bool = True        # .npz per replicate (REQUIRED for repro)
    keep_vtk: bool = False              # VTKs are large; npz supersedes them


@dataclass
class TileSpec:
    sample_id: str
    tile: str          # "r1c2"
    row: int
    col: int
    r0: int
    c0: int
    h: int
    w: int


# ===========================================================================
# Tiling
# ===========================================================================
def split_tiles(shape: Tuple[int, int], grid: int, sample_id: str) -> List[TileSpec]:
    """Non-overlapping GRID x GRID partition of an (H, W) image.

    Remainder rows/columns from integer division are DROPPED (the tiles are
    all exactly the same size). Equal-area tiles matter: a metric measured on
    a larger tile is not exchangeable with one measured on a smaller tile, and
    a rank test assumes exchangeability under the null.
    """
    H, W = shape
    th, tw = H // grid, W // grid
    if th < 64 or tw < 64:
        raise ValueError(
            f"grid={grid} gives {th}x{tw} px tiles -- too small for a stable PSD. "
            "Use a coarser grid or a bigger ROI.")
    tiles = []
    for r in range(grid):
        for c in range(grid):
            tiles.append(TileSpec(
                sample_id=sample_id, tile=f"r{r}c{c}", row=r, col=c,
                r0=r * th, c0=c * tw, h=th, w=tw))
    return tiles


# ===========================================================================
# Per-tile 2D measurement (deterministic -- computed ONCE per tile)
# ===========================================================================
@dataclass
class TileMeasurement:
    tile: TileSpec
    vf2d: Dict[str, float]                  # includes "Unclassified"
    psd: Dict[str, psdmod.PhasePSD]
    psd_ok: bool                            # all phases got a finite (mu, sigma)
    bad_phases: List[str]


def measure_tile(gray_tile: np.ndarray, spec: SampleSpec, tile: TileSpec,
                 cfg: BatchConfig) -> TileMeasurement:
    """Segment + PSD one tile. No randomness here -- one call, reused by all
    replicates of that tile. This is also the expensive-ish CPU step
    (watershed), so computing it once per tile rather than once per replicate
    saves ~90% of the CPU time in a 10-replicate sweep."""
    res = seg.segment_by_thresholds(gray_tile, spec.thresholds(),
                                    fill_unclassified=False)
    vf2d = seg.volume_fractions(res)

    psds: Dict[str, psdmod.PhasePSD] = {}
    bad: List[str] = []
    for name in spec.phase_names:
        p = psdmod.measure_phase(res.masks[name], spec.um_per_px, name,
                                 cfg=cfg.psd_cfg)
        psds[name] = p
        if not (math.isfinite(p.lognormal_mu) and math.isfinite(p.lognormal_sigma)):
            bad.append(name)

    return TileMeasurement(tile=tile, vf2d=vf2d, psd=psds,
                           psd_ok=(len(bad) == 0), bad_phases=bad)


# ===========================================================================
# DREAM.3D pipeline construction -- template-agnostic
# ===========================================================================
# Your two existing modules disagree about filter keys: dream3d.py indexes
# "00"/"01", dream3d_runner.py indexes "0"/"1"/"5". Locating filters by
# Filter_Name instead works with BOTH templates and cannot silently bind to
# the wrong filter.
def _find_filter(pipe: dict, filter_name: str) -> str:
    for k, v in pipe.items():
        if isinstance(v, dict) and v.get("Filter_Name") == filter_name:
            return k
    raise KeyError(f"template has no '{filter_name}' filter")


# ---------------------------------------------------------------------------
# Writing ONE phase into StatsGenerator -- the bins MUST be regenerated
# ---------------------------------------------------------------------------
# THIS IS THE PART THAT IS EASY TO GET WRONG, AND GETTING IT WRONG IS SILENT.
#
# StatsGenerator does NOT sample grain diameters from (Average, StdDev). Those
# two fields are metadata. The diameters actually packed by PackPrimaryPhases
# come from the discretised arrays:
#
#     BinNumber              the bin edges, in DIAMETER units
#     Bin Count              how many bins
#     Feature_Diameter_Info  [bin step, max diameter, min diameter]
#     FeatureSize Vs *       per-bin shape/neighbour arrays, one entry per bin
#
# Set Average/StdDev but leave the bins at the template's defaults, and
# DREAM.3D packs the TEMPLATE's grains while cheerfully reporting your mu and
# sigma. The output looks plausible, the pipeline exits 0, and every volume you
# generate is the same generic microstructure no matter which sample you fed
# it. (Observed: pore came out at ~20% in all three OFA samples against 2D
# inputs of 1.2%, 0.5% and 1.4%, and both solid phases had tau = 1.000 exactly
# in every run -- perfectly straight paths through a structure that was not
# ours.)
#
# So: rebuild the bins from (mu, sigma) every time, and rebroadcast the per-bin
# arrays to the new bin count so their lengths stay consistent. This mirrors
# _regen_size_distribution() in psm/dream3d.py, which had it right.
_CUTOFF_SIGMA = 3.0        # bins span exp(mu +/- 3*sigma)
_NUM_BINS = 10


def _write_phase(s: dict, name: str, frac: float, mu: float, sigma: float) -> None:
    fsd = s.setdefault("FeatureSize Distribution", {})
    # DREAM.3D's JSON parser rejects NaN/Inf tokens; a collapsed lognormal fit
    # must fall back rather than poison the file. psm.batch flags these rows
    # psd_ok=False and psm.stats excludes them.
    if not math.isfinite(mu):
        mu = float(fsd.get("Average", 0.7))
    if not math.isfinite(sigma) or sigma <= 0:
        sigma = float(fsd.get("Standard Deviation", 0.2))

    s["Name"] = name
    s["PhaseFraction"] = float(frac)
    fsd["Average"] = float(mu)
    fsd["Standard Deviation"] = float(sigma)

    minD = float(np.exp(mu - _CUTOFF_SIGMA * sigma))
    maxD = float(np.exp(mu + _CUTOFF_SIGMA * sigma))
    if not (maxD > minD):                       # degenerate (sigma ~ 0)
        maxD = minD * 1.5 + 1e-3
    step = (maxD - minD) / _NUM_BINS
    bins = np.arange(minD, maxD, step)
    if bins.size == 0:
        bins = np.array([minD])
    n_bins = int(bins.size)

    s["BinNumber"] = [float(b) for b in bins]
    s["Bin Count"] = n_bins
    s["Feature_Diameter_Info"] = [float(step), float(maxD), float(minD)]

    # Per-bin arrays must have exactly n_bins entries or DREAM.3D reads past the
    # end / truncates. Broadcast the template's first bin across the new count,
    # which keeps grains roughly equiaxed as the original template intended.
    def _broadcast(dist_key: str, array_keys: list) -> None:
        dist = s.get(dist_key)
        if not isinstance(dist, dict):
            return
        for k in array_keys:
            vals = dist.get(k)
            if isinstance(vals, list) and vals:
                dist[k] = [float(vals[0])] * n_bins

    _broadcast("FeatureSize Vs B Over A Distributions", ["Alpha", "Beta"])
    _broadcast("FeatureSize Vs C Over A Distributions", ["Alpha", "Beta"])
    _broadcast("FeatureSize Vs Omega3 Distributions", ["Alpha", "Beta"])
    _broadcast("FeatureSize Vs Neighbors Distributions",
               ["Average", "Standard Deviation"])


def build_pipeline_json(template: str,
                        phases: Sequence[Tuple[str, float, float, float]],
                        out_vtk: str,
                        dims: Tuple[int, int, int],
                        voxel_um: float,
                        json_path: str) -> str:
    """Write a run-ready pipeline JSON. ``phases`` = [(name, frac, mu, sigma)].

    Phase fractions are renormalized to sum to 1.0 (the segmentation leaves an
    "Unclassified" remainder that DREAM.3D must not see).
    """
    with open(template, "r") as f:
        pipe = json.load(f)

    k_stats = _find_filter(pipe, "StatsGeneratorFilter")
    k_init = _find_filter(pipe, "InitializeSyntheticVolume")
    k_vtk = _find_filter(pipe, "VtkRectilinearGridWriter")

    fr = np.array([p[1] for p in phases], dtype=float)
    if fr.sum() <= 0:
        raise ValueError("all phase fractions are zero")
    fr = fr / fr.sum()

    stats = pipe[k_stats]["StatsDataArray"]
    keys = sorted((k for k in stats if k.isdigit()), key=int)
    if len(keys) != len(phases):
        raise ValueError(f"template has {len(keys)} phases, got {len(phases)}")

    for key, (name, _f, mu, sigma), frac in zip(keys, phases, fr):
        _write_phase(stats[key], name, float(frac), float(mu), float(sigma))

    init = pipe[k_init]
    init["Dimensions"] = {"x": int(dims[0]), "y": int(dims[1]), "z": int(dims[2])}
    init["Resolution"] = {"x": float(voxel_um), "y": float(voxel_um),
                          "z": float(voxel_um)}
    d, r = init["Dimensions"], init["Resolution"]
    init["BoxDimensions"] = (
        f"X Range: 0 to {d['x']*r['x']} (Delta: {d['x']*r['x']})\n"
        f"Y Range: 0 to {d['y']*r['y']} (Delta: {d['y']*r['y']})\n"
        f"Z Range: 0 to {d['z']*r['z']} (Delta: {d['z']*r['z']})")

    out_abs = os.path.abspath(out_vtk)
    os.makedirs(os.path.dirname(out_abs), exist_ok=True)
    pipe[k_vtk]["OutputFile"] = out_abs

    # Redirect the other writers too, or they scatter files into the template's
    # directory (or into Dr. Jin's hard-coded C:/Users/xfjin paths).
    side_dir = os.path.join(os.path.dirname(out_abs), "_side")
    os.makedirs(side_dir, exist_ok=True)
    stem = Path(out_abs).stem
    for k, v in pipe.items():
        if not isinstance(v, dict):
            continue
        fn = v.get("Filter_Name")
        if fn == "DataContainerWriter":
            v["OutputFile"] = os.path.join(side_dir, stem + ".dream3d")
        elif fn == "WriteStlFile":
            v["OutputStlDirectory"] = side_dir

    json_abs = os.path.abspath(json_path)
    os.makedirs(os.path.dirname(json_abs), exist_ok=True)
    with open(json_abs, "w") as f:
        json.dump(pipe, f, indent=2)
    return json_abs


# ===========================================================================
# 3D metrics from one generated volume
# ===========================================================================
def metrics_from_volume(vol: np.ndarray, names: Dict[int, str],
                        voxel_um: float,
                        axes: Iterable[int]) -> dict:
    """Tortuosity (per phase, PER AXIS), connectivity, VF, TPB, DPB -> flat dict.

    Tortuosity convention (Dr. Jin): tau >= 1 always; a phase that does not
    percolate along an axis gets tau = INF, not NaN. inf is meaningful ("no
    path exists"); NaN is not, and NaN silently poisons every downstream
    aggregate. This is the only place the convention is applied, so the rest
    of the codebase inherits it for free.
    """
    row: dict = {}

    for name, f in ev.volume_fractions_3d(vol, names).items():
        row[f"vf3d_{name}"] = float(f)

    for ax in axes:
        a = AXIS_NAMES[ax]
        for r in all_phase_tortuosity(vol, names, axis=ax):
            p = r["Phase"]
            perc = bool(r["Percolates"])
            tau = float(r["Tortuosity"])
            row[f"perc_{a}_{p}"] = perc
            row[f"tau_{a}_{p}"] = tau if (perc and math.isfinite(tau)) else float("inf")
            # connectivity is axis-independent; written once, on the first axis
            row.setdefault(f"conn_{p}", float(r["ConnectivityRatio"]))

    b = analyze_boundaries(vol, names, voxel_size_um=voxel_um)
    row["tpb_density_um-2"] = float(b.tpb_density_um_per_um3)
    row["tpb_length_um"] = float(b.tpb_length_um)
    for (x, y), area in b.dpb_area_um2.items():
        row[f"dpb_{x}-{y}_um2"] = float(area)
    return row


# ===========================================================================
# The sweep
# ===========================================================================
# ---------------------------------------------------------------------------
# Config fingerprint -- the resume-safety interlock
# ---------------------------------------------------------------------------
# The runner is resumable: completed (sample, tile, replicate) rows are read
# back from the CSV and skipped. That is what makes a 270-run sweep survivable,
# and it is also a trap: change the ROI, the bands, the calibration or the
# template and rerun, and the old rows -- computed under the OLD config --
# are silently kept and MIXED with new ones. This happened for real: a sweep
# resumed over 27 rows computed with an uncropped ROI, and the poisoned table
# (17.9% pore against a validated 1.19%) was only caught by a diagnostic
# script two runs later.
#
# So every analysis-relevant setting is hashed into a fingerprint stored next
# to the CSV. On startup, a fingerprint mismatch REFUSES to run rather than
# resume -- the one thing the runner must never do is silently mix results
# from two different configurations.
def _config_fingerprint(samples, cfg) -> dict:
    d = {
        "samples": [
            dict(sample_id=s.sample_id, roi=list(s.roi) if s.roi else None,
                 um_per_px=s.um_per_px,
                 bands=[list(b) for b in s.bands])
            for s in sorted(samples, key=lambda x: x.sample_id)
        ],
        "grid": cfg.grid, "dims": list(cfg.dims), "voxel_um": cfg.voxel_um,
        "axes": list(cfg.axes),
        "psd": dict(min_area_px=cfg.psd_cfg.min_area_px,
                    min_diameter_um=cfg.psd_cfg.min_diameter_um,
                    use_watershed=cfg.psd_cfg.use_watershed,
                    h_max=cfg.psd_cfg.h_max),
    }
    try:  # template CONTENTS, not path -- editing the JSON must also trip it
        with open(cfg.template, "rb") as f:
            d["template_sha1"] = hashlib.sha1(f.read()).hexdigest()
    except OSError:
        d["template_sha1"] = "unreadable"
    blob = json.dumps(d, sort_keys=True).encode()
    d["fingerprint"] = hashlib.sha1(blob).hexdigest()
    return d


def _check_fingerprint(out_dir: Path, csv_path: Path, samples, cfg) -> None:
    """Write the fingerprint on a fresh run; refuse to resume over a stale one."""
    fp_path = out_dir / "config_fingerprint.json"
    now = _config_fingerprint(samples, cfg)
    has_results = csv_path.exists()

    if not has_results:
        with open(fp_path, "w") as f:
            json.dump(now, f, indent=2)
        return

    if not fp_path.exists():
        raise RuntimeError(
            f"{csv_path} contains results but has no config fingerprint, so there "
            "is no way to prove they were computed with the current settings.\n"
            "Delete the old results (or move them aside) and rerun:\n"
            f"    Remove-Item -Recurse -Force {out_dir}")

    with open(fp_path) as f:
        old = json.load(f)
    if old.get("fingerprint") != now["fingerprint"]:
        diffs = []
        for k in ("samples", "grid", "dims", "voxel_um", "axes", "psd",
                  "template_sha1"):
            if old.get(k) != now.get(k):
                diffs.append(f"  {k}:\n    was: {old.get(k)}\n    now: {now.get(k)}")
        raise RuntimeError(
            "CONFIG CHANGED SINCE THESE RESULTS WERE COMPUTED -- refusing to "
            "resume, because that would mix rows from two different "
            "configurations into one table.\n\nWhat changed:\n"
            + "\n".join(diffs)
            + f"\n\nEither restore the old config, or start clean:\n"
              f"    Remove-Item -Recurse -Force {out_dir}")


def _done_keys(csv_path: Path) -> set:
    if not csv_path.exists():
        return set()
    try:
        df = pd.read_csv(csv_path, usecols=["sample", "tile", "replicate"])
    except Exception:
        return set()
    return {(str(a), str(b), int(c))
            for a, b, c in zip(df["sample"], df["tile"], df["replicate"])}


def _append_row(csv_path: Path, row: dict) -> None:
    """Append one row, writing the header only if the file is new.

    Appending row-by-row (rather than collecting and writing once at the end)
    is what makes a 270-run sweep survivable: kill it at run 173 and the first
    172 rows are already on disk.
    """
    df = pd.DataFrame([row])
    df.to_csv(csv_path, mode="a", header=not csv_path.exists(), index=False)


def run_batch(samples: Sequence[SampleSpec], cfg: BatchConfig,
              csv_name: str = "metrics_long.csv",
              progress=None) -> pd.DataFrame:
    """Run the full tile x replicate sweep. Resumable. Returns the full table.

    ``progress`` is an optional callable(done:int, total:int, msg:str) so the
    Streamlit page (and the CLI) can share one implementation.
    """
    out_dir = Path(cfg.out_dir)
    (out_dir / "volumes").mkdir(parents=True, exist_ok=True)
    (out_dir / "_work").mkdir(parents=True, exist_ok=True)
    csv_path = out_dir / csv_name

    _check_fingerprint(out_dir, csv_path, samples, cfg)

    done = _done_keys(csv_path)
    total = len(samples) * cfg.grid ** 2 * cfg.replicates
    n = len(done)
    if progress:
        progress(n, total, f"resuming: {n}/{total} already complete")

    for spec in samples:
        gray_full = seg.read_sem_as_gray8(spec.image_path)
        gray = seg.crop_roi(gray_full, spec.roi)
        tiles = split_tiles(gray.shape, cfg.grid, spec.sample_id)

        # label ids follow band order: 1..N, matching segment_by_thresholds
        names = {i: nm for i, nm in enumerate(spec.phase_names, start=1)}

        for t in tiles:
            pending = [k for k in range(cfg.replicates)
                       if (spec.sample_id, t.tile, k) not in done]
            if not pending:
                continue

            sub = gray[t.r0:t.r0 + t.h, t.c0:t.c0 + t.w]
            tm = measure_tile(sub, spec, t, cfg)   # deterministic, once per tile

            phases = [(nm, float(tm.vf2d[nm]),
                       float(tm.psd[nm].lognormal_mu),
                       float(tm.psd[nm].lognormal_sigma))
                      for nm in spec.phase_names]

            for k in pending:
                tag = f"{spec.sample_id}_{t.tile}_rep{k:02d}"
                vtk = out_dir / "_work" / f"{tag}.vtk"
                jsn = out_dir / "_work" / f"{tag}.json"
                try:
                    build_pipeline_json(cfg.template, phases, str(vtk),
                                        cfg.dims, cfg.voxel_um, str(jsn))
                    proc = dr.run_pipeline(str(jsn), cfg.runner_exe)
                    if proc.returncode != 0 or not vtk.exists():
                        raise RuntimeError(
                            f"DREAM.3D exit {proc.returncode}\n"
                            f"{(proc.stdout or '')[-800:]}\n{(proc.stderr or '')[-800:]}")
                    vol = d3d.load_phase_volume_vtk(str(vtk))
                except Exception as e:
                    row = dict(sample=spec.sample_id, tile=t.tile,
                               tile_row=t.row, tile_col=t.col, replicate=k,
                               status="FAILED", error=str(e)[:400],
                               timestamp=datetime.now(timezone.utc).isoformat())
                    _append_row(csv_path, row)
                    n += 1
                    if progress:
                        progress(n, total, f"{tag}: FAILED")
                    continue

                npz = ""
                if cfg.archive_volumes:
                    npz = str(out_dir / "volumes" / f"{tag}.npz")
                    # DREAM.3D generation is NOT reproducible (no seed exposed),
                    # so the volume itself is the primary record. int8 is enough
                    # for 3 phase labels and keeps 270 volumes ~ tens of MB.
                    np.savez_compressed(npz, vol=vol.astype(np.int8))

                row = dict(sample=spec.sample_id, tile=t.tile,
                           tile_row=t.row, tile_col=t.col, replicate=k,
                           status="ok",
                           psd_ok=tm.psd_ok,
                           bad_phases=";".join(tm.bad_phases),
                           um_per_px=spec.um_per_px,
                           voxel_um=cfg.voxel_um,
                           tile_h_px=t.h, tile_w_px=t.w)
                for nm in spec.phase_names:
                    p = tm.psd[nm]
                    row[f"vf2d_{nm}"] = float(tm.vf2d[nm])
                    row[f"mu_{nm}"] = float(p.lognormal_mu)
                    row[f"sigma_{nm}"] = float(p.lognormal_sigma)
                    row[f"meand_{nm}_um"] = float(p.summary["MeanDiameter_um"])
                    row[f"nfeat_{nm}"] = int(p.summary["AcceptedFeatureCount"])
                row["vf2d_Unclassified"] = float(tm.vf2d.get("Unclassified", 0.0))

                row.update(metrics_from_volume(vol, names, cfg.voxel_um, cfg.axes))
                row["volume_npz"] = npz
                row["timestamp"] = datetime.now(timezone.utc).isoformat()

                _append_row(csv_path, row)
                if not cfg.keep_vtk:
                    vtk.unlink(missing_ok=True)
                    jsn.unlink(missing_ok=True)

                n += 1
                if progress:
                    progress(n, total, tag)

    return pd.read_csv(csv_path) if csv_path.exists() else pd.DataFrame()