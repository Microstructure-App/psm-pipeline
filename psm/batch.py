"""
psm.batch -- tile-and-replicate batch runner.  THE STATISTICS ENGINE.

WHY THIS EXISTS
---------------
Only three SEM images exist for this study: one field of view per sample
(OFA8, OFA10, OFA11). Running the wizard once per sample yields ONE number
per metric per sample -- n = 1, on which no statistical test is possible.

This module manufactures legitimate statistical n from those same three
images, by two independent mechanisms:

  1. TILING  -- each image is split into a GRID x GRID array of
     non-overlapping tiles. Each tile is analyzed as an independent
     observation. The spread across tiles measures WITHIN-FIELD spatial
     heterogeneity of the electrode.

  2. REPLICATION -- DREAM.3D's packing RNG is seeded internally from the
     clock (verified: PackPrimaryPhases and InitializeSyntheticVolume expose
     NO seed parameter in the 6.5.171 pipeline JSON). Re-running the same
     pipeline on the same PSD therefore produces a DIFFERENT volume every
     time. The spread across replicates measures RECONSTRUCTION STOCHASTICITY
     -- how much the answer moves with nothing changed.

Together these give n = GRID^2 x REPLICATES observations per sample, enough
for a Kruskal-Wallis test of the question that matters:

    Do OFA8, OFA10 and OFA11 differ by more than within-field heterogeneity
    and reconstruction noise?

WHAT THIS VARIANCE IS *NOT* (state this in the paper, every time)
----------------------------------------------------------------
It is within-field + method variance. It is NOT between-cell or
between-session variance, because only one field of view per sample was
imaged. The test can therefore establish that the imaged regions differ; it
CANNOT rule out systematic cell-to-cell or imaging-session variation. Say so
explicitly in Limitations. An honestly-labelled limitation is forgivable;
the absence of any statistical test is not.

TWO DESIGN RULES THAT PROTECT THE EXPERIMENT
--------------------------------------------
  * Thresholds are FIXED PER SAMPLE and applied identically to every tile of
    that sample. Re-thresholding each tile independently would let the
    segmentation absorb the very heterogeneity we are trying to measure, and
    would confound tile-to-tile differences with threshold differences.

  * Every generated volume is ARCHIVED as a compressed .npz. DREAM.3D's
    generation is not reproducible (no seed), so archiving the volumes is the
    only way the downstream analysis remains reproducible. Without this, the
    numbers in the paper cannot be regenerated by anyone, including you.

OUTPUT
------
One CSV, long by run: exactly one row per (sample, tile, replicate). Columns
carry the 2D inputs (volume fractions, mu, sigma, feature counts), the 3D
outputs (volume fractions, tortuosity PER PHASE PER AXIS, percolation,
connectivity, TPB density, DPB areas), and provenance (archived volume path,
timestamp). Non-percolating phases are recorded as tau = inf, NOT NaN --
Dr. Jin's convention: tau >= 1 always, and inf means the phase cannot
percolate along that axis.

The runner is RESUMABLE: completed (sample, tile, replicate) rows are read
back from the CSV on startup and skipped. A 3-sample x 9-tile x 10-replicate
sweep is 270 DREAM.3D invocations; it will be interrupted.
"""

